def pkg_xml(name: str, purpose: str, dependencies=()) -> str:
    depends = "".join(f"  <exec_depend>{dep}</exec_depend>\n" for dep in dependencies)
    return (f'<?xml version="1.0"?>\n'
            f'<package format="3">\n'
            f'  <name>{name}</name>\n'
            f'  <version>0.1.0</version>\n'
            f'  <description>{purpose}</description>\n'
            f'  <maintainer email="dev@example.invalid">car project</maintainer>\n'
            f'  <license>Apache-2.0</license>\n'
            f'  <buildtool_depend>ament_cmake</buildtool_depend>\n'
            f'{depends}'
            f'  <export><build_type>ament_cmake</build_type></export>\n'
            f'</package>\n')


