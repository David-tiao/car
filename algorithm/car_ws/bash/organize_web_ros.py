def fatal(msg: str) -> None:
    raise RuntimeError(msg)


def write_atomic(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=".organize-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(body)
        os.chmod(temp, 0o755 if path.name == "web.sh" else 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def snapshot_digest(root: Path) -> tuple[int, int, str]:
    hashes = hashlib.sha256()
    size = 0
    count = 0
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root).as_posix()
        if path.is_symlink():
            hashes.update(f"L:{rel}:{os.readlink(path)}\n".encode())
        elif path.is_file():
            count += 1
            size += path.stat().st_size
            hashes.update(f"F:{rel}:".encode())
            with path.open("rb") as f:
                for chunk in iter(lambda: f.read(1 << 20), b""):
                    hashes.update(chunk)
        elif path.is_dir():
            hashes.update(f"D:{rel}\n".encode())
    return count, size, hashes.hexdigest()


def get_mode(legacy: Path, site: Path) -> str:
    if legacy.is_symlink():
        if not site.is_dir() or legacy.resolve() != site.resolve():
            fatal(f"发现未知旧路径软链接（拒绝覆盖）：{legacy} -> {os.readlink(legacy)}")
        return "migrated"
    if legacy.is_dir() and not site.exists():
        return "fresh"
    if not legacy.exists() and site.is_dir():
        return "recover"
    if legacy.is_dir() and site.is_dir():
        fatal(f"原目录与目标目录同时存在，需人工确认（拒绝合并/覆盖）：\n  {legacy}\n  {site}")
    fatal(f"未找到有效 Sim2Real 源目录：{legacy}")


def validate(repo: Path) -> tuple[Path, Path, Path, str]:
    ws = repo / "algorithm/car_ws"
    src = ws / "src"
    legacy = repo / "sim2real"
    site = src / "car_web_sim" / "site"
    if not src.is_dir() or not (ws / "bash").is_dir():
        fatal(f"ROS2 工作空间不存在：{ws} （需要已有 src/ 和 bash/）")
    mode = get_mode(legacy, site)
    origin = legacy if mode == "fresh" else site
    for p in (origin / "server.py", origin / "launcher.py", origin / "web/index.html"):
        if not p.is_file():
            fatal(f"现有网页关键文件缺失：{p}")
    return ws, legacy, site, mode


def preflight(repo: Path, mode: str) -> None:
    paths = generated(repo)
    ws = repo / "algorithm/car_ws"
    allowed = {"car_web_test", "car_web_real", "car_web_sim", "car_web_keyboard"}
    # Never silently adopt or overwrite existing directories with unrelated files.
    for name in allowed:
        directory = ws / "src" / name
        if not directory.exists():
            continue
        expected = {p.relative_to(directory).parts[0] for p in paths if directory in p.parents}
        expected.add("site" if name == "car_web_sim" else "__never__")
        unfamiliar = {x.name for x in directory.iterdir()} - expected
        if unfamiliar:
            fatal(f"已有 {directory} 且包含非本脚本创建的条目 {sorted(unfamiliar)}；为避免破坏，请人工确认。")
    for path, contents in paths.items():
        if path.is_symlink():
            fatal(f"目标文件是软链接，拒绝覆盖：{path}")
        if path.exists():
            if not path.is_file() or path.read_text(encoding="utf-8") != contents:
                fatal(f"已存在内容不同的文件，拒绝覆盖：{path}")
    local_copy = ws / "bash/organize_web_ros.py"
    if local_copy.exists() and not local_copy.is_file():
        fatal(f"目标不是普通文件：{local_copy}")


def backup_legacy(legacy: Path, repo: Path) -> Path:
    count, size, original_sha = snapshot_digest(legacy)
    if size > 256 * 1024 * 1024:
        fatal(f"Sim2Real 目录约 {size / 1048576:.1f} MiB，自动备份超过 256 MiB 限额；请先自行备份并整理大文件。")
    state = Path.home() / ".local/state/car_web_organizer/backups"
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(state, 0o700)
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    dest = state / stamp
    dest.mkdir(mode=0o700)
    copy = dest / "sim2real_before_move"
    shutil.copytree(legacy, copy, symlinks=True)
    backed = snapshot_digest(copy)
    if backed != (count, size, original_sha):
        shutil.rmtree(dest)
        fatal("备份文件摘要不匹配，已终止迁移。")
    manifest = {"version": VERSION, "repo": str(repo), "origin": str(legacy),
                "backup": str(copy), "files": count, "bytes": size,
                "digest_sha256": original_sha, "created_at": stamp}
    (dest / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.chmod(dest / "manifest.json", 0o600)
    return dest


def apply(repo: Path, ws: Path, legacy: Path, site: Path, mode: str, self_file: Path) -> None:
    preflight(repo, mode)
    backup = None
    if mode == "fresh":
        backup = backup_legacy(legacy, repo)
        print(f"[BACKUP] {backup}")
        site.parent.mkdir(parents=True, exist_ok=True)
        legacy.rename(site)  # same filesystem; no file contents rewritten
        print(f"[MOVE] {legacy}  ->  {site}")
    if mode in ("fresh", "recover"):
        relative = os.path.relpath(site, legacy.parent)
        legacy.symlink_to(relative, target_is_directory=True)
        print(f"[LINK] {legacy} -> {relative}")
    if legacy.resolve() != site.resolve():
        fatal("目录迁移后链接验证失败。")
    for p, data in generated(repo).items():
        if not p.exists():
            write_atomic(p, data)
            print(f"[NEW]  {p.relative_to(repo)}")
    # Install the organizer for future --check/--undo runs; don't overwrite edits.
    target = ws / "bash/organize_web_ros.py"
    if not target.exists():
        shutil.copy2(self_file, target)
        target.chmod(0o755)
        print(f"[NEW]  {target.relative_to(repo)}")
    print("\n[PASS] 目录整理完成；原 Sim2Real 网站数据与旧入口保留。")
    print(f"[CHECK] bash {ws / 'bash/web.sh'} doctor")
    print(f"[BUILD] bash {ws / 'bash/web.sh'} build")
    if backup is not None:
        print(f"[ROLLBACK] python3 {target} --undo")


def undo(repo: Path, ws: Path, legacy: Path, site: Path, mode: str) -> None:
    if mode != "migrated":
        fatal(f"当前迁移状态为 {mode}；仅当旧路径为链接时允许撤销。")
    # Never clobber a real directory that might have been created at old path.
    legacy.unlink()
    try:
        site.rename(legacy)
    except Exception:
        legacy.symlink_to(os.path.relpath(site, legacy.parent), target_is_directory=True)
        raise
    print(f"[UNDO] 已把 Sim2Real 实体（含迁移后的修改）恢复到 {legacy}")
    files = generated(repo)
    for p, contents in files.items():
        if p.is_file() and not p.is_symlink() and p.read_text(encoding="utf-8") == contents:
            p.unlink()
            print(f"[UNDO] 删除未改动的脚手架文件：{p.relative_to(repo)}")
        elif p.exists():
            print(f"[KEEP] 文件已修改，不删除：{p}")
    for name in ("car_web_keyboard", "car_web_test", "car_web_real", "car_web_sim"):
        path = ws / "src" / name
        for folder in (path / "launch", path):
            try:
                folder.rmdir()
            except OSError:
                if folder.exists():
                    print(f"[KEEP] 包目录包含其他内容，不删除：{folder}")
    print("[PASS] 撤销完成。已有 ROS2 包、地图与 STM32F4 未修改。")


def build(ws: Path) -> None:
    if not Path("/opt/ros/humble/setup.bash").is_file():
        fatal("需要 Ubuntu ROS2 Humble 环境；迁移已完成，但未执行 colcon build。")
    command = ("source /opt/ros/humble/setup.bash && "
               "colcon build --packages-up-to car_web_test car_web_real car_web_sim")
    print("[BUILD] 正在构建新建的三个 ROS2 包...")
    subprocess.run(["bash", "-c", command], cwd=ws, check=True)
    print("[PASS] colcon 构建完成")


def main() -> None:
    ap = argparse.ArgumentParser(description="安全整理 car_ws + Sim2Real；不碰 STM32F4")
    ap.add_argument("--repo", type=Path, default=Path.home() / "Desktop/car",
                    help="项目仓库根目录（默认 ~/Desktop/car）")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--dry-run", action="store_true", help="仅预览，无任何写操作")
    g.add_argument("--check", action="store_true", help="检查整理状态")
    g.add_argument("--undo", action="store_true", help="撤销目录迁移，保留后续用户修改")
    ap.add_argument("--build", action="store_true", help="整理后额外构建三个新 ROS2 包")
    args = ap.parse_args()
    if args.build and (args.dry_run or args.check or args.undo):
        ap.error("--build 仅可与默认整理操作一起使用")
    repo = args.repo.expanduser().resolve()
    if not repo.is_dir():
        fatal(f"仓库目录不存在：{repo}")
    ws, legacy, site, mode = validate(repo)
    print(f"[REPO] {repo}\n[WS]   {ws}\n[MODE] {mode}")
    if args.check:
        print("[OK] 网站文件存在。" if mode == "migrated" else "[NOTE] 网站尚未迁移或正在恢复中。")
        for p in generated(repo):
            if p.exists():
                print(f"[EXISTS] {p.relative_to(repo)}")
        return
    if args.dry_run:
        preflight(repo, mode)
        print(f"[PLAN] 原网站实体：{legacy} -> {site}" if mode == "fresh" else "[PLAN] 旧网站目录不需要再次搬迁")
        print("[PLAN] 将创建的 ROS2 包：car_web_test, car_web_real, car_web_sim")
        print("[PLAN] 将预留忽略编译的目录：car_web_keyboard")
        print("[PLAN] 新增统一入口：car_ws/bash/web.sh，不触碰旧脚本")
        print("[PLAN] 保留 ~/Desktop/car/sim2real 的旧路径和 car 网页命令")
        print("[PLAN] STM32F4/、已有 ROS2 包、地图、build/install/log 完全不操作")
        return
    if args.undo:
        undo(repo, ws, legacy, site, mode)
        return
    apply(repo, ws, legacy, site, mode, Path(__file__).resolve())
    if args.build:
        build(ws)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError, subprocess.CalledProcessError) as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        sys.exit(1)
